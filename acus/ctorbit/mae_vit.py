def adapt_patch_embed_rgb_to_gray(state: dict) -> dict:
    """ImageNet MAE is 3-channel. Average RGB kernels into a native 1-channel conv."""
    key = "patch_embed.proj.weight"
    w = state[key]
    if w.ndim == 4 and w.shape[1] == 3:
        state = dict(state)
        state[key] = w.mean(dim=1, keepdim=True)
    return state


def load_mae_encoder(
    checkpoint_path: str,
    img_size: int = 224,
    in_chans: int = 1,
    strict: bool = True,
) -> VisionTransformer:
    model = vit_base_patch16(img_size=img_size, in_chans=in_chans)
    ckpt = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    state = ckpt["model"] if "model" in ckpt else ckpt
    if in_chans == 1:
        state = adapt_patch_embed_rgb_to_gray(state)
    interpolate_pos_embed(model, state)
    missing, unexpected = model.load_state_dict(state, strict=False)
    n_ok = len(model.state_dict()) - len(missing)
    print(f"[MAE] loaded {checkpoint_path}  matched={n_ok} missing={len(missing)} unexpected={len(unexpected)}")
    if in_chans == 1:
        print("[MAE] patch_embed adapted RGB->1ch by averaging kernels (CT/X-ray grayscale)")
    if strict and (missing or unexpected):
        raise RuntimeError(f"MAE load incomplete: missing={missing[:8]} unexpected={unexpected[:8]}")
    return model
